    static let byICAO: [String: Airport] = Dictionary(airports.map { ($0.icao, $0) }, uniquingKeysWith: { a, _ in a })

    /// Look up coordinates; fall back to CLGeocoder so unknown airports still work.
    static func resolve(for clue: PhotoClue) async -> Airport? {
        if !clue.icao.isEmpty, let known = byICAO[clue.icao] { return known }
        let geocoder = CLGeocoder()
        let name = clue.airportName.replacingOccurrences(of: " - (clue.icao)", with: "")
        if let placemarks = try? await geocoder.geocodeAddressString(name), let p = placemarks.first,
           let loc = p.location {
            return Airport(icao: clue.icao, name: name, latitude: loc.coordinate.latitude, longitude: loc.coordinate.longitude)
        }
        return nil
    }
